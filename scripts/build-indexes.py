#!/usr/bin/env python3
"""Compile pinned source data to deterministic Swift indexes, with no network."""
import hashlib, json, pathlib, re
root=pathlib.Path(__file__).resolve().parent.parent
src=root/'data/sources/cmudict.dict'
expected='81917843c7f44ce2b094ac63873c2c7a4cf802040792c455ba3ca406891c3d22'
if hashlib.sha256(src.read_bytes()).hexdigest()!=expected: raise SystemExit('CMU source hash mismatch')
words=set()
for line in src.read_text(encoding='utf-8').splitlines():
    word=line.split(' ',1)[0]
    word=re.sub(r'\(\d+\)$','',word)
    if re.fullmatch(r'[a-z]+',word): words.add(word)
nepali=json.loads((root/'data/sources/nepali-authored-v1.json').read_text())
for k,v in nepali.items():
    if not re.fullmatch(r'[a-z]+',k) or not v or not all(isinstance(x,str) and x for x in v): raise SystemExit('invalid Nepali entry: '+k)
lines=['// Generated by scripts/build-indexes.py. Do not edit.', 'import Foundation', 'enum GeneratedIndexes {', '    static let englishWords: Set<String> = Set(englishText.split(separator: "\\n").map(String.init))', '    static let nepali: [String: [String]] = [']
for key in sorted(nepali):
    lines.append('        '+json.dumps(key,ensure_ascii=False)+': ['+', '.join(json.dumps(v,ensure_ascii=False) for v in nepali[key])+'],')
lines.extend(['    ]','    private static let englishText = """','\n'.join(sorted(words)),'"""','}'])
out='\n'.join(lines)+'\n'
(root/'Sources/NepaliCore/GeneratedIndexes.swift').write_text(out,encoding='utf-8')
print(f'Generated {len(words)} English forms and {len(nepali)} Nepali keys, {len(out.encode())} bytes')
